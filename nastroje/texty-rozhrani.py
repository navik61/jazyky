def main() -> None:
    cil = Path(__file__).resolve().parent.parent / "locale"
    cil.mkdir(exist_ok=True)
    for i, kod in enumerate(JAZYKY):
        with (cil / f"{kod}.tsv").open("w", encoding="utf-8") as f:
            f.write(f"# Texty rozhraní ({kod}) — generuje nastroje/texty-rozhrani.py, ruční úpravy dělej tam\n")
            for klic, preklady in TEXTY.items():
                assert len(preklady) == len(JAZYKY), klic
                assert "\t" not in preklady[i] and "\n" not in preklady[i], klic
                f.write(f"{klic}\t{preklady[i]}\n")
    print(f"{len(TEXTY)} klíčů × {len(JAZYKY)} jazyků → {cil}")


if __name__ == "__main__":
    main()
